// Turn the single-colour SVGs in public/brand/ into lib/brand/shapes.ts so the
// same geometry can be drawn as inline SVG (UI) and with Path2D (print canvas).
// usage: node scripts/brand/build-shapes.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const dir = path.join(root, "public/brand");

const NAMES = {
  "logo-primary.svg": "logoPrimary",
  "logo-tertiary.svg": "logoTertiary",
  "medallion.svg": "medallion",
  "star.svg": "star",
  "loop-brace-open.svg": "braceOpen",
  "loop-brace-close.svg": "braceClose",
  "loop-bracket-open.svg": "bracketOpen",
  "loop-bracket-close.svg": "bracketClose",
  "loops-paren-x3.svg": "parenX3",
  "loops-bracket-x3.svg": "bracketX3",
  "loops-brace-x3.svg": "braceX3",
};

const entries = Object.entries(NAMES).map(([file, name]) => {
  const svg = fs.readFileSync(path.join(dir, file), "utf8");
  const [x, y, w, h] = /viewBox="([^"]+)"/.exec(svg)[1].split(/\s+/).map(Number);
  const paths = [...svg.matchAll(/<path([^>]*)>/g)].map(([, attrs]) => {
    const d = /\sd="([^"]+)"/.exec(attrs)[1];
    const evenodd = /fill-rule="evenodd"/.test(attrs);
    return { d, evenodd };
  });
  return { name, x, y, w, h, paths };
});

const out = `// Generated by scripts/brand/build-shapes.mjs from public/brand/*.svg. Do not edit.

export interface BrandShape {
  /** viewBox origin and size */
  x: number;
  y: number;
  w: number;
  h: number;
  paths: { d: string; evenodd: boolean }[];
}

${entries
  .map(
    (e) =>
      `export const ${e.name}: BrandShape = {\n  x: ${e.x},\n  y: ${e.y},\n  w: ${e.w},\n  h: ${e.h},\n  paths: [\n${e.paths
        .map((p) => `    { evenodd: ${p.evenodd}, d: ${JSON.stringify(p.d)} },`)
        .join("\n")}\n  ],\n};`
  )
  .join("\n\n")}
`;

fs.mkdirSync(path.join(root, "lib/brand"), { recursive: true });
fs.writeFileSync(path.join(root, "lib/brand/shapes.ts"), out);
console.log(`wrote lib/brand/shapes.ts (${entries.length} shapes, ${out.length} bytes)`);
